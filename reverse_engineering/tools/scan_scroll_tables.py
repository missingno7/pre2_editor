#!/usr/bin/env python3
"""Probe PRE2_load.bin for scroll/camera helper data.

The flat unpacked module mixes code and data.  This tool makes the current
status reproducible: we can confirm whether small tables copied from the
blues-master reference are visible as exact contiguous byte arrays in the load
module before treating them as ASM-confirmed.
"""
from __future__ import annotations

from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BLOB = ROOT / "disasm" / "PRE2_load.bin"
DS_BASE = 0x9860

VSCROLL_OFFSETS_DATA = bytes((
    0x01,0x01,0x01,0x01,0x01,0x01,0x02,0x02,0x02,0x02,0x02,0x02,0x02,0x02,0x02,0x02,
    0x02,0x02,0x02,0x02,0x02,0x02,0x02,0x02,0x03,0x03,0x03,0x03,0x03,0x03,0x03,0x03,
    0x03,0x03,0x03,0x03,0x03,0x03,0x03,0x03,0x03,0x03,0x03,0x03,0x03,0x03,0x03,0x03,
    0x03,0x03,0x03,0x04,0x04,0x04,0x04,0x04,0x04,0x04,0x04,0x04,0x04,0x04,0x04,0x04,
    0x05,0x05,0x05,0x05,0x05,0x05,0x05,0x05,0x05,0x06,0x06,0x06,0x06,0x06,0x06,0x06,
    0x07,0x07,0x07,0x07,0x07,0x07,0x08,0x08,0x08,0x09,0x09,0x09,0x0A,0x0A,0x0B,0x0B,
    0x0C,0x0D,0x0E,0x10,0x10,0x10,0x10,0x10,0x10,0x10,0x10,0x10,0x10,0x10,0x10,0x10,
    0x10,0x10,0x10,0x10,0x10,0x10,0x10,0x10,0x10,0x10,0x10,0x10,0x10,0x10,0x10,0x10,
    0x10,0x10,0x10,0x10,
))

# Compact signatures from level_update_scrolling/level_adjust_y_scroll constants.
SIGNATURES = {
    "vscroll_offsets_full_132": VSCROLL_OFFSETS_DATA,
    "vscroll_offsets_head_32": VSCROLL_OFFSETS_DATA[:32],
    "vscroll_offsets_mid_ramp": VSCROLL_OFFSETS_DATA[80:104],
    "vscroll_offsets_tail_16s": bytes([0x10] * 24),
    "camera_keyboard_thresholds": bytes([0x09, 0x03, 0x08, 0x02, 0x0A, 0x08, 0x07, 0x06]),
}


def find_all(blob: bytes, needle: bytes) -> list[int]:
    out: list[int] = []
    start = 0
    while True:
        pos = blob.find(needle, start)
        if pos < 0:
            return out
        out.append(pos)
        start = pos + 1


def main() -> int:
    blob = BLOB.read_bytes()
    print(f"blob: {BLOB} ({len(blob)} bytes)")
    for name, needle in SIGNATURES.items():
        hits = find_all(blob, needle)
        print(f"{name}: {len(hits)} hit(s)")
        for pos in hits[:16]:
            ds = pos - DS_BASE
            ds_text = f"DS:{ds:04X}" if 0 <= ds <= 0xFFFF else "outside DGROUP"
            print(f"  file 0x{pos:05X}  {ds_text}")
        if len(hits) > 16:
            print("  ...")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
